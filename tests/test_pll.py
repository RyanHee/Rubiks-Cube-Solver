"""All 21 CubeSkills PLL diagrams must solve using their printed algorithms.

Fixtures are explicit facelets read from the sheet, not scrambles generated by
Cube.move(). See tests/fixtures/README.md for notation and verification details.
"""

from collections import Counter
import json
from pathlib import Path
import unittest

import numpy as np

from rubiks_cube.cube import Cube


FIXTURE_PATH = Path(__file__).resolve().parent / 'fixtures/pll_cases.json'
FIXTURES = json.loads(FIXTURE_PATH.read_text())
FACE_ORDER = FIXTURES['face_order']
SOLVED = np.array([
    [[FIXTURES['solved_colors'][face]] * 3 for _ in range(3)]
    for face in FACE_ORDER
])
EXPECTED_CASES = {
    'Aa', 'Ab', 'E', 'F', 'Ga', 'Gb', 'Gc', 'Gd', 'H', 'Ja', 'Jb',
    'Na', 'Nb', 'Ra', 'Rb', 'T', 'Ua', 'Ub', 'V', 'Y', 'Z',
}


def initial_state(case):
    return np.array([
        [list(row) for row in case['initial_faces'][face]]
        for face in FACE_ORDER
    ])


class PLLFixtureTests(unittest.TestCase):
    def test_all_21_cases_are_present_once(self):
        names = [case['name'] for case in FIXTURES['cases']]
        self.assertEqual(set(names), EXPECTED_CASES)
        self.assertEqual(len(names), len(EXPECTED_CASES))

    def test_starting_states_have_solved_f2l_and_oriented_last_layer(self):
        for case in FIXTURES['cases']:
            with self.subTest(case=case['name']):
                state = initial_state(case)
                self.assertEqual(state.shape, (6, 3, 3))
                self.assertFalse(np.array_equal(state, SOLVED))
                self.assertEqual(Counter(state.flat), Counter(SOLVED.flat))
                np.testing.assert_array_equal(state[0], SOLVED[0])
                np.testing.assert_array_equal(state[5], SOLVED[5])
                np.testing.assert_array_equal(state[1:5, 1:], SOLVED[1:5, 1:])
                np.testing.assert_array_equal(state[:, 1, 1], SOLVED[:, 1, 1])

    def test_facelets_match_transcribed_diagram_bars(self):
        for case in FIXTURES['cases']:
            with self.subTest(case=case['name']):
                for face, bar in case['diagram_bars'].items():
                    # Back and right strips run backwards in a top-down view.
                    if face in 'BR':
                        bar = bar[::-1]
                    row = ''.join(case['diagram_color_map'][color] for color in bar)
                    self.assertEqual(case['initial_faces'][face][0], row)


class PLLMovementTests(unittest.TestCase):
    """One separately named movement regression test for each PLL case."""


def pll_test(case):
    def test(self):
        cube = Cube(initial_state(case))
        for move in case['outer_algorithm'].split():
            self.assertRegex(move, r"^[RLUDFB](?:2|')?$")
            cube.move(move)
        np.testing.assert_array_equal(
            cube.cube, SOLVED,
            err_msg=f"{case['name']} PLL did not solve. Sheet: {case['algorithm']}\n"
                    f"Outer-face sequence: {case['outer_algorithm']}",
        )

    test.__doc__ = f"Solve the {case['name']} diagram using {case['algorithm']}"
    return test


for case in FIXTURES['cases']:
    setattr(PLLMovementTests, f"test_{case['name']}_solves_cube", pll_test(case))


if __name__ == '__main__':
    unittest.main()
